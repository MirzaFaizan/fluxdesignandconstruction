#!/usr/bin/env node
/**
 * FluX responsive renditions.
 *
 * Reads the committed launch set (every WebP under web-media/launch/) and
 * writes width-stepped AVIF + WebP renditions to public/media/r/,
 * plus src/lib/media-manifest.generated.ts so the app knows each image's
 * size, widths and content hash. Runs as `prebuild`, so `next build` and the
 * OpenNext deploy always have the files. Output files are content-addressed
 * (hash of the source in the name), so an existing file is a valid cache and
 * the `_headers` rule can mark them immutable.
 *
 * Never upscales. The source-width WebP is copied, not re-encoded.
 */
import { createHash } from "node:crypto";
import {
  copyFile,
  mkdir,
  readFile,
  readdir,
  rename,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "../..");
const LAUNCH = path.join(ROOT, "web-media/launch");
const OUT = path.join(ROOT, "public/media/r");
const TS_OUT = path.join(ROOT, "src/lib/media-manifest.generated.ts");

const WIDTHS = [480, 768, 960, 1200, 1600, 1920];
const AVIF = { quality: 72, effort: 3, chromaSubsampling: "4:2:0" };
const WEBP = { quality: 88, effort: 5, smartSubsample: true };
const CONCURRENCY = Math.max(2, Math.min(os.cpus().length, 8));

// Hash covers the encoder settings too, so a quality change busts caches.
const SETTINGS_KEY = JSON.stringify({ WIDTHS, AVIF, WEBP });

function hashFile(buf) {
  return createHash("sha1")
    .update(buf)
    .update(SETTINGS_KEY)
    .digest("hex")
    .slice(0, 8);
}

function widthsFor(sourceWidth) {
  return [...WIDTHS.filter((w) => w < sourceWidth), sourceWidth];
}

async function exists(file) {
  return stat(file).then(
    () => true,
    () => false,
  );
}

async function pool(items, worker) {
  const queue = [...items];
  const results = [];
  const runners = Array.from({ length: CONCURRENCY }, async () => {
    while (queue.length) {
      const item = queue.shift();
      results.push(await worker(item));
    }
  });
  await Promise.all(runners);
  return results;
}

async function listSources() {
  const files = [];
  for (const folder of await readdir(LAUNCH, { withFileTypes: true })) {
    if (!folder.isDirectory()) continue;
    for (const name of await readdir(path.join(LAUNCH, folder.name))) {
      if (name.endsWith(".webp")) files.push(path.join(LAUNCH, folder.name, name));
    }
  }
  return files.sort();
}

// Write via a temp name so an interrupted run never leaves a truncated file
// that the existence check would then treat as done.
async function encode(pipeline, out) {
  const tmp = `${out}.tmp`;
  await pipeline.toFile(tmp);
  await rename(tmp, out);
}

async function renderItem(webpSrc) {
  const id = path.basename(webpSrc, ".webp");
  const buf = await readFile(webpSrc);
  // The pipeline's own AVIF (from the master) is better than re-encoding the
  // WebP at full size, so copy it when it is there.
  const avifSrc = webpSrc.replace(/\.webp$/, ".avif");
  const avifBuf = await readFile(avifSrc).catch(() => null);
  const hash = hashFile(avifBuf ? Buffer.concat([buf, avifBuf]) : buf);
  const { width, height } = await sharp(buf).metadata();
  const widths = widthsFor(width);
  const files = [];
  let written = 0;

  for (const w of widths) {
    const h = Math.round((height * w) / width);
    const base = path.join(OUT, `${id}.${hash}-${w}`);
    const avifOut = `${base}.avif`;
    const webpOut = `${base}.webp`;
    files.push(path.basename(avifOut), path.basename(webpOut));

    const needAvif = !(await exists(avifOut));
    const needWebp = !(await exists(webpOut));
    if (!needAvif && !needWebp) continue;

    if (w === width) {
      if (needWebp) await copyFile(webpSrc, webpOut);
      if (needAvif && avifBuf) await copyFile(avifSrc, avifOut);
      else if (needAvif) await encode(sharp(buf).avif(AVIF), avifOut);
    } else {
      const resized = sharp(buf).resize({ width: w, height: h, fit: "fill" });
      if (needAvif) await encode(resized.clone().avif(AVIF), avifOut);
      if (needWebp) await encode(resized.clone().webp(WEBP), webpOut);
    }
    written += Number(needAvif) + Number(needWebp);
  }

  return { id, hash, width, height, widths, files, written };
}

function renderTs(entries) {
  const lines = entries
    .sort((a, b) => a.id.localeCompare(b.id))
    .map(
      (e) =>
        `  "${e.id}": { hash: "${e.hash}", width: ${e.width}, height: ${e.height}, widths: [${e.widths.join(", ")}] },`,
    );
  return [
    "// Generated by scripts/image-pipeline/renditions.mjs. Do not edit.",
    "// Run `npm run media` after changing web-media/.",
    "",
    'export const MEDIA_BASE = "/media/r";',
    "",
    "export const MEDIA = {",
    ...lines,
    "} as const;",
    "",
    "export type MediaId = keyof typeof MEDIA;",
    "",
  ].join("\n");
}

async function main() {
  await mkdir(OUT, { recursive: true });

  const started = Date.now();
  const entries = await pool(await listSources(), renderItem);

  const keep = new Set(entries.flatMap((e) => e.files));
  let removed = 0;
  for (const name of await readdir(OUT)) {
    if (!keep.has(name)) {
      await rm(path.join(OUT, name));
      removed += 1;
    }
  }

  const ts = renderTs(entries);
  const current = await readFile(TS_OUT, "utf8").catch(() => "");
  if (current !== ts) await writeFile(TS_OUT, ts);

  let bytes = 0;
  for (const name of keep) bytes += (await stat(path.join(OUT, name))).size;
  const written = entries.reduce((s, e) => s + e.written, 0);
  console.log(
    `renditions: ${entries.length} images, ${keep.size} files, ${(bytes / 1e6).toFixed(1)} MB in ${path.relative(ROOT, OUT)}/ (${written} written, ${removed} stale removed, ${((Date.now() - started) / 1000).toFixed(1)}s)`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
